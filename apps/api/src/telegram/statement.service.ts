import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';

export interface StatementRow {
  createdAt: Date;
  type: string;
  payeeName: string;
  amount: unknown;
  currency: string;
  status: string;
  paypalRef: string | null;
}

export interface StatementInput {
  periodLabel: string;
  rows: StatementRow[];
  pendingCount: number;
  contactCount: number;
}

function money(amount: unknown, currency: string): string {
  const n = Number(amount);
  try {
    return new Intl.NumberFormat('en-US', {
      style: 'currency',
      currency,
      maximumFractionDigits: 2,
    }).format(Number.isFinite(n) ? n : 0);
  } catch {
    return `${currency} ${Number.isFinite(n) ? n.toFixed(2) : '0.00'}`;
  }
}

@Injectable()
export class StatementService {
  build(input: StatementInput): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ size: 'A4', margin: 48 });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      doc.fontSize(20).text('ArkPay', { continued: false });
      doc.fontSize(12).fillColor('#555').text('Account statement');
      doc.moveDown(0.3);
      doc.fontSize(10).fillColor('#333').text(`Period: ${input.periodLabel}`);
      doc.text(`Generated: ${new Date().toISOString().replace('T', ' ').slice(0, 16)} UTC`);
      doc.moveDown(1);

      const invoices = input.rows.filter((r) => r.type === 'INVOICE');
      const payouts = input.rows.filter((r) => r.type !== 'INVOICE');
      const sum = (rows: StatementRow[]) =>
        rows.reduce((total, r) => total + Number(r.amount ?? 0), 0);

      doc.fontSize(12).fillColor('#000').text('Summary', { underline: true });
      doc.moveDown(0.3);
      doc.fontSize(10).fillColor('#333');
      doc.text(`Invoices: ${invoices.length} · ${money(sum(invoices), 'USD')}`);
      doc.text(`Payouts: ${payouts.length} · ${money(sum(payouts), 'USD')}`);
      doc.text(`Pending approvals: ${input.pendingCount}`);
      doc.text(`Contacts: ${input.contactCount}`);
      doc.moveDown(1);

      doc.fontSize(12).fillColor('#000').text('Actions', { underline: true });
      doc.moveDown(0.4);

      const header = (y: number) => {
        doc.fontSize(8).fillColor('#666');
        doc.text('Date', 48, y, { width: 70 });
        doc.text('Type', 118, y, { width: 80 });
        doc.text('Payee', 198, y, { width: 150 });
        doc.text('Amount', 348, y, { width: 90, align: 'right' });
        doc.text('Status', 438, y, { width: 70 });
        doc.text('Ref', 508, y, { width: 40 });
      };

      header(doc.y);
      doc.moveDown(0.4);
      let y = doc.y;
      for (const row of input.rows.slice(0, 60)) {
        if (y > 760) {
          doc.addPage();
          header(48);
          y = doc.y + 10;
        }
        const date = row.createdAt.toISOString().slice(0, 10);
        doc.fontSize(8).fillColor('#222');
        doc.text(date, 48, y, { width: 70 });
        doc.text(row.type.replace('PAYOUT_', ''), 118, y, { width: 80 });
        doc.text(row.payeeName.slice(0, 32), 198, y, { width: 150 });
        doc.text(money(row.amount, row.currency), 348, y, {
          width: 90,
          align: 'right',
        });
        doc.text(row.status, 438, y, { width: 70 });
        doc.text(row.paypalRef?.slice(-10) ?? '—', 508, y, { width: 40 });
        y += 16;
      }

      if (input.rows.length === 0) {
        doc.fontSize(10).fillColor('#666').text('No actions in this period.');
      }

      doc.moveDown(1);
      doc
        .fontSize(8)
        .fillColor('#888')
        .text(
          'Generated by ArkPay. Amounts are in their original currency. This statement is an operational record, not a tax document.',
          48,
          790,
          { width: 500, align: 'center' },
        );

      doc.end();
    });
  }
}
